const supported = new Set(PDF_FONT_RANGES.flatMap(([start, end]) => Array.from({ length: end - start + 1 }, (_, i) => start + i)));

/** Distinct characters in the given text that the PDF font cannot draw. Line breaks and tabs are fine. */
export function unsupportedPdfChars(...texts: string[]): string[] {
  const chars = new Set<string>();
  for (const char of texts.join("").normalize("NFC")) {
    const cp = char.codePointAt(0)!;
    if (cp !== 0x09 && cp !== 0x0a && cp !== 0x0d && !supported.has(cp)) chars.add(char);
  }
  return [...chars];
}
